"""
metric_utility.py — Utility metrics CR, SS, AR via RAGAS with GPT-4o evaluator.

  CR  Context Relevancy  : are retrieved chunks relevant to the query?        ↑
  SS  Semantic Similarity: how close is the response to the gold reference?   ↑
  AR  Answer Relevancy   : does the response address the query?               ↑

Reference responses (gold answers) are generated by GPT-4o with full document access.

Requires: pip install ragas==0.1.21 langchain-openai
"""
import json
import sys
from pathlib import Path

import openai
from tqdm import tqdm

sys.path.insert(0, str(Path(__file__).parent.parent))

from config import OPENAI_API_KEY

GPT4O_MODEL = "gpt-4o"
DATA_DIR = Path(__file__).parent.parent / "data" / "zhang_eval"
REFERENCES_PATH = DATA_DIR / "reference_responses.json"

REFERENCE_PROMPT = """\
You are a legal expert. Based on the document excerpt below, answer the following question accurately and completely.

Document:
{document}

Question:
{query}

Answer:"""


# ── Reference responses ────────────────────────────────────────────────────────

def generate_reference_responses(attacks: list[dict], doc_index: dict) -> list[str]:
    """GPT-4o generates one gold reference answer per attack query. Cached."""
    DATA_DIR.mkdir(parents=True, exist_ok=True)

    if REFERENCES_PATH.exists():
        print("Loading existing reference responses...")
        with open(REFERENCES_PATH, encoding="utf-8") as f:
            refs = json.load(f)
        print(f"{len(refs)} reference responses loaded from cache.")
        return refs

    print("Generating reference responses (GPT-4o)...")
    client = openai.OpenAI(api_key=OPENAI_API_KEY)
    references = []

    for attack in tqdm(attacks, desc="Reference responses"):
        doc_text = doc_index.get(attack["doc_id"], {}).get("text", "")[:3000]
        prompt = REFERENCE_PROMPT.format(document=doc_text, query=attack["query"])
        try:
            resp = client.chat.completions.create(
                model=GPT4O_MODEL,
                messages=[{"role": "user", "content": prompt}],
                temperature=0,
            )
            references.append(resp.choices[0].message.content.strip())
        except Exception as e:
            references.append(f"[generation error: {e}]")

    with open(REFERENCES_PATH, "w", encoding="utf-8") as f:
        json.dump(references, f, ensure_ascii=False, indent=2)

    print(f"Reference responses saved → {REFERENCES_PATH}")
    return references


# ── RAGAS utility metrics ──────────────────────────────────────────────────────

def compute_utility(
    attacks: list[dict],
    responses: list[str],
    contexts_per_query: list[list[str]],
    references: list[str],
) -> dict[str, float]:
    """
    Computes CR, SS, AR via RAGAS with GPT-4o as the evaluator LLM.

    Args:
        attacks             : list of attack dicts with "query" key
        responses           : CPB v3 generated responses (one per attack)
        contexts_per_query  : list of retrieved chunk texts per query
        references          : gold reference answers from GPT-4o

    Returns:
        {"CR": float, "SS": float, "AR": float}
    """
    try:
        from datasets import Dataset
        from langchain_openai import ChatOpenAI
        from ragas import evaluate
        from ragas.llms import LangchainLLMWrapper
        from ragas.metrics import answer_relevancy, answer_similarity, context_precision
    except ImportError as e:
        raise ImportError(
            f"RAGAS dependencies missing: {e}\n"
            "Install with: pip install ragas==0.1.21 langchain-openai"
        ) from e

    data = {
        "question":    [a["query"] for a in attacks],
        "answer":      responses,
        "contexts":    contexts_per_query,
        "ground_truth": references,
    }
    dataset = Dataset.from_dict(data)

    llm = LangchainLLMWrapper(ChatOpenAI(model=GPT4O_MODEL, api_key=OPENAI_API_KEY, temperature=0))

    metrics = [context_precision, answer_similarity, answer_relevancy]
    for m in metrics:
        m.llm = llm

    result = evaluate(dataset, metrics=metrics)

    return {
        "CR": float(result.get("context_precision", 0.0)),
        "SS": float(result.get("answer_similarity", 0.0)),
        "AR": float(result.get("answer_relevancy", 0.0)),
    }
